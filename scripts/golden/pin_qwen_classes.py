"""Materialize the installed HF regex engine's Unicode classes for ICU, independently of the corpus."""
import argparse
from pathlib import Path

import tokenizers
from tokenizers import Regex, pre_tokenizers

if tokenizers.__version__ != "0.23.3":
    raise SystemExit("review property tables before changing the reference version")


def icu_class(pattern):
    split = pre_tokenizers.Split(Regex(pattern + "+"), "removed", invert=True)
    ranges = []
    # Offsets for Python pre-tokenizers are Unicode scalar positions.
    for start, stop in [(0, 0xD800), (0xE000, 0x110000)]:
        for lo in range(start, stop, 8192):
            chunk = "".join(map(chr, range(lo, min(lo + 8192, stop))))
            for _, (begin, end) in split.pre_tokenize_str(chunk):
                first, last = lo + begin, lo + end - 1
                if ranges and ranges[-1][1] == first - 1:
                    ranges[-1] = ranges[-1][0], last
                else:
                    ranges.append((first, last))

    def esc(c):
        return rf"\x{{{c:X}}}"

    return "".join(esc(a) if a == b else esc(a) + "-" + esc(b) for a, b in ranges)


def main():
    root = Path(__file__).resolve().parents[2]
    default = root / "Sources/EmbedCore/Tokenizer/HFClasses.swift"
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=default)
    args = parser.parse_args()
    with args.output.open("w", encoding="ascii", newline="\n") as out:
        print("// Generated by scripts/golden/pin_qwen_classes.py from Hugging Face tokenizers 0.23.3.", file=out)
        print("enum HFClasses {", file=out)
        for name, pattern in [("letter", r"\p{L}"), ("number", r"\p{N}"), ("space", r"\s")]:
            print(f'    static let {name} = #"{icu_class(pattern)}"#', file=out)
        print("}", file=out)


if __name__ == "__main__":
    main()
